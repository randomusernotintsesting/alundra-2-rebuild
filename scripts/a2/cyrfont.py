"""Cyrillic glyph builder for the Alundra 2 ASCII font banks.

Approach: the 96-cell ASCII banks (12x16 dialogue, 12x24 subtitle) are kept
at their original size; 66 cells whose Latin glyphs are unused by the JP
game text (letters + rare symbols) are redrawn as Cyrillic. Variable per-
glyph width is preserved. No SCPS code patches are required.

Cell map (cell = char byte - 0x20 inside the bank; token = 0xFF00|char):
  А..Щ -> 'A'..'Z' cells (0x41-0x5A), ЪЫЬЭЮЯ -> '[\\]^_`', Ё -> '@'
  а..щ -> 'a'..'z' cells (0x61-0x7A), ъыьэю -> '{|}~' + 0x7F,
  я -> '#', ё -> '$'
Digits, space and common punctuation keep their Latin glyphs.

Glyphs reuse identical Latin shapes where possible (А=A, В=B, ...),
mirror/compose others (И=mirror N, Я=mirror R, Ч from H, ...), and the
rest are drawn by hand in the same style.  Lowercase letters that have no
Latin lookalike are mostly "squashed" x-height versions of the capitals.
"""

W = 12

# ---------------- pixel ops ----------------

def decode_bank(data, h, n=96):
    rec = h * 3 + 1
    out = []
    for g in range(n):
        off = g * rec
        px = []
        for row in range(h):
            rowpx = []
            for byte in data[off + row * 3: off + row * 3 + 3]:
                rowpx += [(byte >> 6) & 3, (byte >> 4) & 3, (byte >> 2) & 3, byte & 3]
            px.append(rowpx)
        out.append((px, data[off + h * 3]))
    return out


def encode_glyph(px, width, h):
    out = bytearray()
    for row in range(h):
        for c in range(0, 12, 4):
            out.append((px[row][c] << 6) | (px[row][c + 1] << 4)
                       | (px[row][c + 2] << 2) | px[row][c + 3])
    out.append(width)
    return bytes(out)


def blank(h):
    return [[0] * W for _ in range(h)]


def art(s, h, top=0):
    """ASCII art ('.'=0, '1'..'3') -> 12xH pixels, first art line at row `top`."""
    px = blank(h)
    for r, ln in enumerate(s.strip("\n").split("\n")):
        for c, ch in enumerate(ln[:W]):
            if ch in "123":
                px[top + r][c] = int(ch)
    return px


def copy(px):
    return [row[:] for row in px]


def bbox_w(px):
    w = 0
    for row in px:
        for c in range(W - 1, -1, -1):
            if row[c]:
                w = max(w, c + 1)
                break
    return w


def hmirror(px, width=None):
    if width is None:
        width = bbox_w(px)
    out = blank(len(px))
    for r, row in enumerate(px):
        for c in range(width):
            out[r][width - 1 - c] = row[c]
    return out


def shift(px, dr=0, dc=0):
    h = len(px)
    out = blank(h)
    for r in range(h):
        for c in range(W):
            if px[r][c] and 0 <= r + dr < h and 0 <= c + dc < W:
                out[r + dr][c + dc] = px[r][c]
    return out


def erase(px, r0, r1, c0, c1):
    px = copy(px)
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            px[r][c] = 0
    return px


def cols(px, c0, c1):
    out = blank(len(px))
    for r in range(len(px)):
        for c in range(c0, c1 + 1):
            out[r][c] = px[r][c]
    return out


def overlay(base, *tops):
    out = copy(base)
    for top in tops:
        for r in range(len(base)):
            for c in range(W):
                if top[r][c]:
                    out[r][c] = top[r][c]
    return out


def squash(px, keep_rows, dest_top):
    out = blank(len(px))
    for i, r in enumerate(keep_rows):
        out[dest_top + i] = px[r][:]
    return out


# ---------------- cell layout ----------------

_UP = "АБВГДЕЖЗИЙКЛМНОПРСТУФХЦЧШЩ"
_LO = "абвгдежзийклмнопрстуфхцчшщ"
CELLS = {}
for _i, _c in enumerate(_UP):
    CELLS[_c] = 0x41 + _i
for _i, _c in enumerate("ЪЫЬЭЮЯ"):
    CELLS[_c] = 0x5B + _i
CELLS["Ё"] = 0x40
for _i, _c in enumerate(_LO):
    CELLS[_c] = 0x61 + _i
for _i, _c in enumerate("ъыьэю"):
    CELLS[_c] = 0x7B + _i
CELLS["я"] = 0x23
CELLS["ё"] = 0x24


def charmap():
    """char -> 16-bit token value (lo = char byte in the bank, hi = 0xFF)."""
    return {c: 0xFF00 | v for c, v in CELLS.items()}


