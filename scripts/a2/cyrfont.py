# ---------------- bank assembly ----------------

def build_bank(bank_bytes, h, builder):
    """Return new bank bytes with Cyrillic cells replaced."""
    latin = decode_bank(bank_bytes, h)
    glyphs = builder(latin)
    out = bytearray(bank_bytes)
    rec = h * 3 + 1
    for ch, cell in CELLS.items():
        px, wid = glyphs[ch]
        idx = cell - 0x20
        out[idx * rec:(idx + 1) * rec] = encode_glyph(px, wid, h)
    return bytes(out)


def build_banks(bank548, bank545):
    """(dialogue 12x16 bytes, subtitle 12x24 bytes) -> patched pair."""
    return (build_bank(bank548, 16, build16),
            build_bank(bank545, 24, build24))
