#!/usr/bin/env python3
"""Link real dispatch tables without compiling the recompiled guest bodies."""
import argparse
import re
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--gen", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    modules = ("scps", "game00", "event00", "game01", "game02", "game03")
    output = ["/* Generated by tests/make_dispatch_fixture.py. */"]
    seen = set()
    for module in modules:
        source = (args.gen / f"{module}_table.c").read_text()
        entries = re.findall(r"\{\s*(0x[0-9a-fA-F]+)u,\s*(\w+)\s*\}", source)
        declared = re.search(rf"const int {module}_table_n = (\d+);", source)
        if not declared or len(entries) != int(declared[1]):
            raise ValueError(f"Unrecognized or incomplete table: {module}")
        for _, function in entries:
            if function in seen:
                raise ValueError(f"Duplicate guest symbol: {function}")
            seen.add(function)
            # Each target has a distinct observable result and function address.
            output.append(f"void {function}(void) {{ R[2] = {len(seen)}u; }}")
        output.append(f'#include "{module}_table.c"')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(output) + "\n")
    print(f"Dispatch fixture: {len(seen)} distinct targets from six real tables")


if __name__ == "__main__":
    main()
